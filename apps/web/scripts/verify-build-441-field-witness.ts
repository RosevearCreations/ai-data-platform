import assert from "node:assert/strict";
import {reconcileBuild441} from "../lib/build441-independent-field-witness";
import {BUILD_438_PROFILES} from "../lib/build438-interface-drift-observatory";
const now=new Date("2026-11-23T23:00:00.000Z");
const source=BUILD_438_PROFILES.map(p=>({appId:p.appId,release:p.buildLabel,state:"REVIEW_REQUIRED" as const,reason:"SIGNED_SOURCE_VERIFIED_INTERFACE_AND_OWNER_ACCEPTANCE_PENDING",receiptId:"receipt-"+p.appId,sourceCommit:p.mainCommit==="SELF_AT_RUNTIME"?"a".repeat(40):p.mainCommit,verifiedAt:"2026-11-23T22:59:00.000Z"}));
const evidence=source.map(s=>({appId:s.appId,sourceCommit:s.sourceCommit,witnessId:"independent-"+s.appId,witnessRole:"independent-observer",originalDeviceId:"original-"+s.appId,observedAt:"2026-11-23T22:59:00.000Z",signatureVerified:true,independentOfSource:true,interfaceCertified:true,receiverAckVerified:true,ownerAcceptanceVerified:true,revoked:false}));
assert.equal(reconcileBuild441(source,[],now).certified,0);
const valid=reconcileBuild441(source,evidence,now);
assert.equal(valid.certified,7);
assert.equal(valid.graph.safeToPromote,true);
assert.equal(valid.rolloutState,"READY_FOR_SOURCE_AUTHORIZED_ROLLOUT");
assert.equal(valid.automaticActionsPerformed,0);
const forged=reconcileBuild441(source,evidence.map(e=>e.appId==="rosevear-ai-hub"?{...e,signatureVerified:false}:e),now);
assert.equal(forged.rows.find(r=>r.appId==="rosevear-ai-hub")?.state,"HOLD");
assert.equal(forged.graph.releases.find(r=>r.appId==="ai-data-platform")?.state,"BLOCKED_BY_DEPENDENCY");
assert.equal(reconcileBuild441(source,evidence.map(e=>({...e,observedAt:"2026-11-23T22:00:00.000Z"})),now).certified,0);
const wrong=reconcileBuild441(source,evidence.map(e=>e.appId==="yw"?{...e,sourceCommit:"b".repeat(40)}:e),now);
assert.equal(wrong.rows.find(r=>r.appId==="yw")?.reason,"WITNESS_SOURCE_COMMIT_MISMATCH");
const duplicated=reconcileBuild441(source,[...evidence,evidence[0]],now);
assert.equal(duplicated.rows.find(r=>r.appId===evidence[0].appId)?.state,"HOLD");
const denied=reconcileBuild441(source.map(s=>s.appId==="icamp"?{...s,state:"HOLD" as const,reason:"SIGNATURE_UNVERIFIED"}:s),evidence,now);
assert.equal(denied.rows.find(r=>r.appId==="icamp")?.state,"HOLD");
console.log("Build 441 independent witness, stale/forged/revoked, source-bound and dependency checks passed.");
