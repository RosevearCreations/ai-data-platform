import assert from "node:assert/strict";
import {build445MaskedEmail,build445OwnerCeremony,build445ProviderState} from "../lib/build445-owner-recovery-contract";
assert.equal(build445MaskedEmail("jf-name@example.com"),"jf***@example.com");
assert.equal(build445MaskedEmail(""),"not available");
assert.equal(build445ProviderState("delivered"),"PROVIDER_DELIVERED_NOT_MAILBOX_PROVEN");
assert.equal(build445ProviderState("bounced"),"PROVIDER_FAILED");
assert.equal(build445ProviderState("sent"),"PENDING_OR_DELAYED");
assert.equal(build445ProviderState(null),"NOT_CHECKED");
const baseline=build445OwnerCeremony({credential:true,ownerRole:true,emailVerified:false,providerAccepted:false,passwordResetCompleted:false,providerLastEvent:null,ownerSessionVerified:false});
assert.equal(baseline.completed,false);
assert.equal(baseline.providerAcceptance,"NOT_ACCEPTED_OR_NOT_REQUESTED");
const sent=build445OwnerCeremony({credential:true,ownerRole:true,emailVerified:false,providerAccepted:true,passwordResetCompleted:false,providerLastEvent:"delivered",ownerSessionVerified:false});
assert.equal(sent.completed,false);
assert.equal(sent.deliveryState,"PROVIDER_DELIVERED_NOT_MAILBOX_PROVEN");
assert.equal(sent.recoveryTransaction,"AWAITING_VERIFIED_RESET");
const reset=build445OwnerCeremony({credential:true,ownerRole:true,emailVerified:false,providerAccepted:true,passwordResetCompleted:true,providerLastEvent:"delivered",ownerSessionVerified:false});
assert.equal(reset.completed,false);
const closed=build445OwnerCeremony({credential:true,ownerRole:true,emailVerified:false,providerAccepted:true,passwordResetCompleted:true,providerLastEvent:"delivered",ownerSessionVerified:true});
assert.equal(closed.completed,true);
assert.equal(closed.independentFieldAcceptance,"HOLD_PENDING_GENUINE_ORIGINAL_DEVICE_PROOFS");
console.log("Build 445 owner identity, provider acceptance vs delivery and authenticated reset continuity tests passed.");
