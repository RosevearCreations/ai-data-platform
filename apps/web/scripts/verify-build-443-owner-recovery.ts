import assert from "node:assert/strict";
import {build443TrustedOrigins,build443Diagnostics} from "../lib/build443-owner-auth-diagnostics";
import {requireBuild443WitnessBinding} from "../lib/build443-witness-key-custody";
import {BUILD_442_SCHEMA,type WitnessEnvelope} from "../lib/build442-witness-crypto";
const base="https://ai-data-platform-johns-projects-8f256ece.vercel.app";
const origins=build443TrustedOrigins(base,"https://operator.example");
assert.ok(origins.includes(base));
assert.ok(origins.includes("https://ai-data-platform-beryl.vercel.app"));
assert.equal(origins.filter(x=>x===base).length,1);
assert.throws(()=>build443TrustedOrigins(base,"https://evil.example/steal"));
assert.throws(()=>build443TrustedOrigins(base,"javascript:alert(1)"));
assert.equal(build443Diagnostics(base,origins,false,false,false,false).loginOriginAllowed,true);
assert.equal(build443Diagnostics("https://attacker.example",origins,true,true,false,false).loginOriginAllowed,false);
assert.equal(build443Diagnostics(null,origins,false,false,false,false).recoveryMailConfigured,false);
const witness:WitnessEnvelope={schema:BUILD_442_SCHEMA,appId:"yw",sourceCommit:"a".repeat(40),witnessId:"witness-A",witnessRole:"independent-observer",originalDeviceId:"original-device-1",observedAt:"2026-11-24T12:00:00.000Z",nonce:"0123456789abcdef01234567",interfaceCertified:true,receiverAckVerified:true,ownerAcceptanceVerified:true,keyId:"keyA",signature:"signed"};
const binding={keyA:{appIds:["yw"],originalDeviceId:"original-device-1",witnessId:"witness-A",witnessRole:"independent-observer",independentOfSource:true,active:true}};
assert.equal(requireBuild443WitnessBinding(witness,binding).appId,"yw");
assert.throws(()=>requireBuild443WitnessBinding({...witness,originalDeviceId:"other-device"},binding));
assert.throws(()=>requireBuild443WitnessBinding({...witness,appId:"icamp"},binding));
assert.throws(()=>requireBuild443WitnessBinding(witness,{keyA:{...binding.keyA,active:false}}));
assert.throws(()=>requireBuild443WitnessBinding(witness,{}));
console.log("Build 443 exact trusted origin, non-disclosing recovery and independent witness binding checks passed.");
